import gradio as gr
import plotly.express as px

def create_plots(x_axis_metric):
    # 1. Bar Plot: Average sales per City
    df_city_sales = df.groupby('City')['sales'].mean().reset_index().sort_values(by='sales', ascending=False)
    fig_bar = px.bar(
        df_city_sales,
        x='City',
        y='sales',
        title='Average Sales by City',
        labels={'sales': 'Average Sales'},
        color='sales',
        color_continuous_scale='Viridis'
    )
    fig_bar.update_layout(xaxis_tickangle=-45)

    # 2. Scatter Plot: Selected advertising budget vs Sales colored by City
    fig_scatter = px.scatter(
        df,
        x=x_axis_metric,
        y='sales',
        color='City',
        title=f'{x_axis_metric} Advertising Budget vs. Sales by City',
        labels={'sales': 'Sales', x_axis_metric: f'{x_axis_metric} Budget'},
        hover_data=['latitude', 'longitude']
    )

    return fig_bar, fig_scatter

# Create the Gradio Interface
with gr.Blocks() as demo:
    gr.Markdown("# 📊 City Sales & Advertising Dashboard")
    gr.Markdown("Analyze how sales change across cities and explore correlations between different advertising mediums and sales.")

    with gr.Row():
        metric_dropdown = gr.Dropdown(
            choices=['TV', 'radio', 'newspaper'],
            value='TV',
            label='Select Advertising Channel for Scatter Plot'
        )

    with gr.Row():
        plot_bar = gr.Plot(label="Average Sales by City")
        plot_scatter = gr.Plot(label="Sales vs. Budget")

    # Define interactions
    metric_dropdown.change(fn=create_plots, inputs=metric_dropdown, outputs=[plot_bar, plot_scatter])

    # Load default plots on startup
    demo.load(fn=create_plots, inputs=metric_dropdown, outputs=[plot_bar, plot_scatter])

# Launch the interface
demo.launch(debug=True)

